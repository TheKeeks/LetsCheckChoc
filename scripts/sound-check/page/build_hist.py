"""Write research/hist.js: the history the Sound Check page shows, as the constants its code reads, from the files
in data/history/ (which the history bot keeps current):

  DATA       results4.json: every day since 2016 (daily), the month-by-month counts (ym), climatology, storms (events),
             periods, good-day shares, the ratings model; plus the sessions' correlations from sessions_all.json
  WILDSTATS  wild_stats.json        DAYS2  days2.json        TRAINS  trains_days.json
  BENT       bend_days.json         WIND   windgrid_out.json SESSPAIRS sess_pairs.json

The page build (build13.py) leaves hist.js alone, so rebuilding the page never rolls the history back.

  python3 scripts/sound-check/page/build_hist.py [OUT]     (default research/hist.js)
"""
import json, os, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
HIST = os.path.join(ROOT, 'data', 'history')

def read(name, hdir=HIST):
    return open(os.path.join(hdir, name)).read().strip()

def build(hdir=HIST):
    r = json.loads(read('results4.json', hdir))
    sess = json.loads(read('sessions_all.json', hdir))['res']
    data = dict(daily=r['daily'], clim=r['clim'], ym=r['ym'], events=r['events'], per=r['per'], good=r['good'], model=r['model'],
                sess=[[k, v['rho'], v['lo'], v['hi']] for k, v in sorted(sess.items(), key=lambda kv: -kv[1]['rho'])])
    js = '// Generated by scripts/sound-check/page/build_hist.py from data/history/ (the history bot keeps both current).\n'
    js += 'const DATA=' + json.dumps(data, separators=(',', ':')) + ';\n'
    js += 'const WILDSTATS=' + read('wild_stats.json', hdir) + ';\n'
    js += 'const DAYS2=' + read('days2.json', hdir) + ';\nconst TRAINS=' + read('trains_days.json', hdir) + ';\n'
    js += 'const BENT=' + read('bend_days.json', hdir) + ';\nconst WIND=' + read('windgrid_out.json', hdir) + ';\n'
    js += 'const SESSPAIRS=' + read('sess_pairs.json', hdir) + ';\n'   # [date, size rating, buoy ft, Choc ft] per logged session (best 3 h)
    return js

if __name__ == '__main__':
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'research', 'hist.js')
    js = build()
    open(out, 'w').write(js)
    print('hist.js bytes', len(js))
